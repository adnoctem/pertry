// Package report renders an analysis as SCHEMA.md and compares a rendered report with a
// committed one.
//
// The output is a pure function of the analysis: rows are sorted by identity, paths are
// relative, and there are no timestamps, machine paths or line numbers. Tables are padded the
// way Prettier pads them, so that a module repository that formats Markdown with Prettier does
// not turn every `formr check` into drift.
package report

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/adnoctem/pertry/internal/formr/addr"
	"github.com/adnoctem/pertry/internal/formr/analysis"
	"github.com/adnoctem/pertry/internal/formr/diag"
	"github.com/adnoctem/pertry/internal/formr/module"
	"github.com/adnoctem/pertry/internal/formr/schema"
)

// FormatVersion is the report format. It changes when a row's meaning changes, so that a
// baseline written by an older formr is recognisably older rather than silently different.
const FormatVersion = 1

// Input is what a report is rendered from.
type Input struct {
	Analysis      *analysis.Result
	Provenance    schema.Provenance
	SchemaFormat  string
	ExtraWarnings []string
}

// Render produces SCHEMA.md.
func Render(in Input) string {
	var b strings.Builder

	b.WriteString("<!-- Generated by formr. Do not edit; regenerate with `formr schema`. -->\n\n")
	b.WriteString("# Provider schema coverage\n\n")
	fmt.Fprintf(&b, "Report format %d. Every field of every provider configuration, resource and data source this module uses, "+
		"and what the module does with it. A traced reference is evidence of a dependency, not proof that a caller controls "+
		"the field's whole domain.\n\n", FormatVersion)

	renderProvenance(&b, in)
	renderSummary(&b, in.Analysis)
	renderDiagnostics(&b, in.Analysis.Diagnostics, in.ExtraWarnings)
	renderProviders(&b, in.Analysis.Providers)
	renderDeclarations(&b, in.Analysis.Declarations)

	return strings.TrimRight(b.String(), "\n") + "\n"
}

func renderProvenance(b *strings.Builder, in Input) {
	b.WriteString("## Provenance\n\n")

	rows := [][]string{}
	engine := "unknown"
	if in.Provenance.Engine.Name != "" {
		engine = in.Provenance.Engine.Name + " " + in.Provenance.Engine.Version
	}
	// Whether the schemas came from an engine or a snapshot is deliberately not recorded: the
	// same schemas must produce the same report either way, or a CI job checking against a
	// snapshot would drift from a baseline generated with the engine.
	rows = append(rows,
		[]string{"Engine", engine},
		[]string{"Schema format", in.SchemaFormat},
	)

	providers := map[string]bool{}
	for _, p := range in.Analysis.Providers {
		providers[p.Provider.String()] = true
	}
	for _, d := range in.Analysis.Declarations {
		providers[d.Provider.String()] = true
	}
	names := make([]string, 0, len(providers))
	for p := range providers {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, name := range names {
		p, _ := addr.ParseProvider(name)
		release, ok := in.Provenance.Providers[p]
		if !ok {
			release = "unknown (not in the lock file)"
		}
		rows = append(rows, []string{code(name), release})
	}

	writeTable(b, []string{"Item", "Value"}, rows)
}

type counter struct {
	keys   []string
	counts map[string]int
}

func newCounter(keys ...string) *counter { return &counter{keys: keys, counts: map[string]int{}} }

func (c *counter) add(k string) { c.counts[k]++ }

func (c *counter) total() int {
	n := 0
	for _, v := range c.counts {
		n += v
	}

	return n
}

func (c *counter) String() string {
	parts := make([]string, 0, len(c.keys))
	for _, k := range c.keys {
		parts = append(parts, fmt.Sprintf("%d %s", c.counts[k], k))
	}

	return strings.Join(parts, ", ")
}

func renderSummary(b *strings.Builder, res *analysis.Result) {
	b.WriteString("## Summary\n\n")

	nodes, leaves := 0, 0
	resIn := newCounter(string(analysis.Direct), string(analysis.Transformed), string(analysis.Derived),
		string(analysis.Fixed), string(analysis.Omitted), string(analysis.Unresolved))
	resOut := newCounter(string(analysis.Exported), string(analysis.PartiallyExported), string(analysis.Internal), string(analysis.Unused))
	dataIn := newCounter(string(analysis.Direct), string(analysis.Transformed), string(analysis.Derived),
		string(analysis.Fixed), string(analysis.Omitted), string(analysis.Unresolved))
	dataOut := newCounter(string(analysis.Exported), string(analysis.PartiallyExported), string(analysis.Internal), string(analysis.Unused))
	providerFields := newCounter(string(analysis.CallerOwned), string(analysis.Direct), string(analysis.Transformed),
		string(analysis.Derived), string(analysis.Fixed), string(analysis.Omitted), string(analysis.Unresolved))

	for _, d := range res.Declarations {
		in, out := resIn, resOut
		if d.Addr.Kind == addr.KindData {
			in, out = dataIn, dataOut
		}
		for _, f := range d.Fields {
			nodes++
			if f.Node.Container {
				continue
			}
			leaves++
			if f.Input != analysis.NotConfigurable {
				in.add(string(f.Input))
			}
			if f.Usage != analysis.NotReadable {
				out.add(string(f.Usage))
			}
		}
	}
	for _, p := range res.Providers {
		for _, f := range p.Fields {
			nodes++
			if !f.Node.Container {
				leaves++
				providerFields.add(string(f.Input))
			}
		}
	}

	inventory := fmt.Sprintf("complete: %d nodes, %d leaves", nodes, leaves)
	if res.Diagnostics.HasErrors() {
		inventory = fmt.Sprintf("**incomplete**: %d nodes, %d leaves listed; see Diagnostics", nodes, leaves)
	}

	writeTable(b, []string{"Measurement", "Leaves", "Breakdown"}, [][]string{
		{"Inventory", strconv.Itoa(leaves), inventory},
		{"Resource inputs", strconv.Itoa(resIn.total()), resIn.String()},
		{"Resource results", strconv.Itoa(resOut.total()), resOut.String()},
		{"Data-source selectors", strconv.Itoa(dataIn.total()), dataIn.String()},
		{"Data-source results", strconv.Itoa(dataOut.total()), dataOut.String()},
		{"Provider configuration", strconv.Itoa(providerFields.total()), providerFields.String()},
	})
}

func renderDiagnostics(b *strings.Builder, diags diag.Diagnostics, extra []string) {
	b.WriteString("## Diagnostics\n\n")

	sorted := diags.Sorted()
	if len(sorted) == 0 && len(extra) == 0 {
		b.WriteString("None.\n\n")

		return
	}

	for _, w := range extra {
		fmt.Fprintf(b, "- **warning** (`.`): %s\n", escape(w))
	}
	for _, d := range sorted {
		fmt.Fprintf(b, "- **%s** (`%s`): %s\n", d.Severity, d.Module, escape(d.Summary))
	}
	b.WriteString("\n")
}

func renderProviders(b *strings.Builder, providers []analysis.ProviderConfig) {
	b.WriteString("## Provider configuration\n\n")
	if len(providers) == 0 {
		b.WriteString("None.\n\n")

		return
	}

	for _, p := range providers {
		title := p.Provider.String()
		if p.Alias != "" {
			title += " (alias " + p.Alias + ")"
		}
		fmt.Fprintf(b, "### %s\n\n", code(title))

		switch p.Owner {
		case module.OwnerCaller:
			b.WriteString("Configured by the caller. These fields are the caller's to set, not missing module inputs.\n\n")
		default:
			fmt.Fprintf(b, "Configured in %s.\n\n", code(p.Location))
		}
		if p.SchemaMissing {
			b.WriteString("**No schema was available for this provider.**\n\n")
			continue
		}
		if len(p.Fields) == 0 {
			b.WriteString("The provider has no configuration fields.\n\n")
			continue
		}

		rows := make([][]string, 0, len(p.Fields))
		for _, f := range p.Fields {
			rows = append(rows, []string{code(f.Node.Path.String()), code(f.Node.Type), f.Node.Flags.String(), inputCell(f), f.Node.Fingerprint})
		}
		writeTable(b, []string{"Field", "Type", "Flags", "Input", "Fingerprint"}, rows)
	}
}

func renderDeclarations(b *strings.Builder, decls []analysis.Declaration) {
	b.WriteString("## Declarations\n\n")
	if len(decls) == 0 {
		b.WriteString("None.\n\n")

		return
	}

	for _, d := range decls {
		fmt.Fprintf(b, "### %s\n\n", code(d.Addr.String()))
		fmt.Fprintf(b, "- Provider: %s\n", code(d.Provider.String()))
		switch {
		case !d.InstancesConditional:
			b.WriteString("- Instances: always one\n")
		case len(d.Instances) == 0:
			b.WriteString("- Instances: fixed by `count` or `for_each`\n")
		default:
			fmt.Fprintf(b, "- Instances: conditional on %s\n", codeList(d.Instances))
		}
		b.WriteString("\n")

		if d.SchemaMissing {
			b.WriteString("**No schema was available for this type.**\n\n")
			continue
		}

		rows := make([][]string, 0, len(d.Fields))
		for _, f := range d.Fields {
			rows = append(rows, []string{
				code(f.Node.Path.String()),
				code(f.Node.Type),
				f.Node.Flags.String(),
				inputCell(f),
				dash(string(f.Availability)),
				dash(string(f.Usage)),
				string(f.Review),
				f.Node.Fingerprint,
			})
		}
		writeTable(b, []string{"Field", "Type", "Flags", "Input", "Availability", "Result", "Review", "Fingerprint"}, rows)
	}
}

func inputCell(f analysis.Field) string {
	switch f.Input {
	case analysis.NotConfigurable:
		return "—"
	case analysis.Omitted, analysis.Fixed, analysis.CallerOwned, analysis.Present:
		return string(f.Input)
	case analysis.Unresolved:
		return "unresolved: " + escape(strings.Join(f.Unresolved, "; "))
	}

	cell := string(f.Input) + ": " + codeList(f.Origins)
	if len(f.ForcedKeys) > 0 {
		cell += "; forces " + codeList(f.ForcedKeys)
	}

	return cell
}

func dash(s string) string {
	if s == "" {
		return "—"
	}

	return s
}

func code(s string) string {
	if s == "" {
		return ""
	}

	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}

func codeList(items []string) string {
	parts := make([]string, len(items))
	for i, s := range items {
		parts[i] = code(s)
	}

	return strings.Join(parts, ", ")
}

// escape neutralises the Markdown that could break a table cell or a list item.
func escape(s string) string {
	r := strings.NewReplacer("|", `\|`, "\n", " ", "*", `\*`, "_", `\_`, "`", "'", "<", "&lt;", ">", "&gt;")

	return r.Replace(s)
}

// writeTable pads every column to its widest cell, as Prettier does.
func writeTable(b *strings.Builder, header []string, rows [][]string) {
	widths := make([]int, len(header))
	for i, h := range header {
		widths[i] = max(3, width(h))
	}
	for _, r := range rows {
		for i, c := range r {
			widths[i] = max(widths[i], width(c))
		}
	}

	line := func(cells []string) {
		b.WriteString("|")
		for i, c := range cells {
			b.WriteString(" ")
			b.WriteString(c)
			b.WriteString(strings.Repeat(" ", widths[i]-width(c)))
			b.WriteString(" |")
		}
		b.WriteString("\n")
	}

	line(header)
	sep := make([]string, len(header))
	for i := range header {
		sep[i] = strings.Repeat("-", widths[i])
	}
	line(sep)
	for _, r := range rows {
		line(r)
	}
	b.WriteString("\n")
}

// width counts runes, which is what Prettier pads by for the characters a report contains.
func width(s string) int { return len([]rune(s)) }
